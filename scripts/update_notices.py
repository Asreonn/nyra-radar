#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_NOTICES.md from references/manifest.json.

For every project marked `adapted`, the LICENSE text is read from the cloned
reference checkout, which must be at the pinned commit. If the checkout is
missing or at a different commit, the script fails, so notices never drift
from the code they cover. Run: `python scripts/update_notices.py [--check]`.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "references" / "manifest.json"
OUT = ROOT / "THIRD_PARTY_NOTICES.md"


def head_commit(path: Path) -> str | None:
    try:
        return subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def render() -> str:
    data = json.loads(MANIFEST.read_text())
    lines = [
        "# Third-Party Notices",
        "",
        "Generated by `scripts/update_notices.py` from `references/manifest.json`. Do not edit by hand.",
        "",
        "Nyra Radar is an independent implementation. The projects below were studied as references.",
        "Where a *permissively licensed* project's algorithm or constants were adapted, its copyright",
        "and license notice is reproduced here, as that license requires. Projects without a clear",
        "license were used only for high-level ideas; none of their source was copied.",
        "",
        "## Runtime dependencies",
        "",
        "Python and npm dependencies are installed from their registries under their own licenses",
        "(see `pyproject.toml` and `apps/web/package.json`). None of them are vendored into this repository.",
        "",
    ]
    for proj in data["projects"]:
        lines += [f"## {proj['name']} ({proj['repo']})", "",
                  f"- Commit inspected: `{proj['commit']}`",
                  f"- License: {proj['license']}",
                  f"- Use in Radar: **{proj['reuse']}**", ""]
        if proj["adapted"]:
            lines.append("Adapted elements:")
            lines.append("")
            lines += [f"- {a}" for a in proj["adapted"]]
            lines.append("")
        if proj["reuse"] == "adapted":
            checkout = ROOT / "references" / proj["dir"]
            sha = head_commit(checkout)
            if sha != proj["commit"]:
                raise SystemExit(f"{proj['name']}: checkout at {sha}, manifest pins {proj['commit']}")
            text = (checkout / proj["license_file"]).read_text().strip()
            lines += ["```text", text, "```", ""]
        else:
            lines += ["No code, constants or text were copied from this project.", ""]
    for ex in data.get("excluded", []):
        lines += [f"## Excluded: {ex['name']}", "", ex["reason"], ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("THIRD_PARTY_NOTICES.md is stale; run scripts/update_notices.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
